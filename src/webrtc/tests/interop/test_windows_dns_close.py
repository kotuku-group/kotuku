#!/usr/bin/env python3
"""Observe public close during a delayed Windows OS resolver query, using a temporary exact-name NRPT rule.

Requires elevation and an unused IPv6 loopback UDP port 53. Does not change adapter DNS settings.
Requires close/free to complete within 500 ms while the OS DNS reply remains delayed by two seconds.
"""
import argparse
from pathlib import Path
import json
import queue
import secrets
import socket
import struct
import subprocess
import tempfile
import threading
import time

from test_windows_notifications import powershell


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--probe', type=Path, required=True)
    parser.add_argument('--destroy', action='store_true', help='Free directly instead of closing first')
    parser.add_argument('--capacity', action='store_true', help='Saturate and cancel 32 forward lookup requests')
    args = parser.parse_args()
    host = f'kotuku-interop-{secrets.token_hex(8)}.invalid'
    rule = None
    process = None
    with socket.socket(socket.AF_INET6, socket.SOCK_DGRAM) as dns, tempfile.TemporaryDirectory() as directory:
        dns.bind(('::1', 53))
        dns.settimeout(10)
        try:
            rule = powershell(f"(Add-DnsClientNrptRule -Namespace '{host}' -NameServers '::1' "
                              "-Comment 'Temporary Kotuku DNS teardown fixture' -PassThru).Name").strip()
            if not rule:
                raise RuntimeError('NRPT did not return the created rule identity')
            config = Path(directory) / 'dns.json'
            config.write_text(json.dumps([{'url': f'turn:{host}:3478', 'username': 'test', 'credential': 'test'}]))
            process = subprocess.Popen([str(args.probe.resolve()), str(config),
                                        'dns-capacity' if args.capacity else 'dns-free' if args.destroy else 'dns-close',
                                        '--log-warning'],
                                       stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
            lines = queue.Queue()
            output = []
            def read_output():
                for line in process.stdout:
                    lines.put(line)
                lines.put(None)
            reader = threading.Thread(target=read_output, daemon=True)
            reader.start()
            request, sender = dns.recvfrom(4096)
            labels = b''.join(bytes([len(label)]) + label.encode() for label in host.split('.')) + b'\0'
            if request[12:12 + len(labels)] != labels:
                raise RuntimeError('Unexpected DNS query reached fixture')
            while True:
                line = lines.get(timeout=10)
                if line is None:
                    raise RuntimeError('Probe exited before close began')
                output.append(line)
                if 'DNS_CLOSE_READY' in line:
                    break
            # Hold the actual OS request past the close call, then return NXDOMAIN for A/AAAA and retries.
            time.sleep(2)
            queries = 0
            deadline = time.monotonic() + 10
            dns.settimeout(0.1)
            while process.poll() is None and time.monotonic() < deadline:
                if request:
                    response = (request[:2] + struct.pack('!HHHHH', 0x8183, 1, 0, 0, 0)
                                + request[12:12 + len(labels) + 4])
                    dns.sendto(response, sender)
                    queries += 1
                try:
                    request, sender = dns.recvfrom(4096)
                except (socket.timeout, ConnectionResetError):
                    request = None
            result = process.wait(timeout=5)
            reader.join(timeout=2)
            while not lines.empty():
                line = lines.get_nowait()
                if line:
                    output.append(line)
            print(''.join(output), end='')
            if result or not any('PASS delayed DNS' in line for line in output):
                raise RuntimeError(f'Delayed DNS probe failed with exit {result}')
            print(f'PASS observed {queries} DNS queries, delayed actual OS response by 2 seconds')
        finally:
            if process:
                if process.poll() is None:
                    process.kill()
                process.wait(timeout=5)
                process.stdout.close()
            if rule:
                # Rule identity is generated by Windows, not supplied by a caller.
                escaped = rule.replace("'", "''")
                powershell(f"Remove-DnsClientNrptRule -Name '{escaped}' -Force; "
                           f"if (Get-DnsClientNrptRule | Where-Object Name -eq '{escaped}') "
                           "{ throw 'NRPT rule cleanup failed' }")
    print('PASS temporary DNS rule removed')


if __name__ == '__main__':
    main()
